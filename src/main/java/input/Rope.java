    /**
     * Holds the cos and sin tables, both shaped [seqLen][headDim].
     */
    public static class RopeCache {
        public final double[][] cos;
        public final double[][] sin;

        public RopeCache(double[][] cos, double[][] sin) {
            this.cos = cos;
            this.sin = sin;
        }
    }

    /**
     * 1. build_rope_cache(seq_len, head_dim, theta_base) -> cos, sin
     * Built once per sequence, reused for every layer / every q and k.
     */
    public static RopeCache buildRopeCache(int seqLen, int headDim, double thetaBase) {
        int half = headDim / 2;

        // inv_freq[i] = 1 / theta_base^(2i / head_dim)
        double[] invFreq = new double[half];
        for (int i = 0; i < half; i++) {
            invFreq[i] = 1.0 / Math.pow(thetaBase, (2.0 * i) / headDim);
        }

        // full_angle[m][j]: same angle repeated in the first and second half
        double[][] fullAngle = new double[seqLen][headDim];
        for (int m = 0; m < seqLen; m++) {
            for (int i = 0; i < half; i++) {
                double angle = m * invFreq[i];
                fullAngle[m][i] = angle;
                fullAngle[m][i + half] = angle;
            }
        }

        double[][] cos = new double[seqLen][headDim];
        double[][] sin = new double[seqLen][headDim];
        for (int m = 0; m < seqLen; m++) {
            for (int j = 0; j < headDim; j++) {
                cos[m][j] = Math.cos(fullAngle[m][j]);
                sin[m][j] = Math.sin(fullAngle[m][j]);
            }
        }

        return new RopeCache(cos, sin);
    }

    /**
     * 2. rotate_half(x) -> x rearranged
     * [x1, x2] -> [-x2, x1]. Swap halves, negate the one that moves to front.
     */
    public static double[][] rotateHalf(double[][] x) {
        int seqLen = x.length;
        int headDim = x[0].length;
        int half = headDim / 2;

        double[][] out = new double[seqLen][headDim];
        for (int m = 0; m < seqLen; m++) {
            for (int i = 0; i < half; i++) {
                out[m][i] = -x[m][i + half];
                out[m][i + half] = x[m][i];
            }
        }
        return out;
    }

    /**
     * 3. apply_rope_single(x, cos, sin) -> x_rotated
     * Called once for q, once for k, with the same cos/sin cache.
     */
    public static double[][] applyRopeSingle(double[][] x, double[][] cos, double[][] sin) {
        double[][] rotated = rotateHalf(x);
        int seqLen = x.length;
        int headDim = x[0].length;

        double[][] xRotated = new double[seqLen][headDim];
        for (int m = 0; m < seqLen; m++) {
            for (int j = 0; j < headDim; j++) {
                xRotated[m][j] = x[m][j] * cos[m][j] + rotated[m][j] * sin[m][j];
            }
        }
        return xRotated;
    }

